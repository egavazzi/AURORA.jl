"""
    AuroraModel{AG, EG, PAG, SD, IO, SP, FT, V}

Container for the grids, atmosphere, and collision data used by an AURORA simulation.
"""
mutable struct AuroraModel{AG<:AltitudeGrid, EG<:EnergyGrid, PAG<:PitchAngleGrid,
                            SD<:ScatteringData, IO<:Ionosphere,
                            SP<:Tuple{Vararg{NeutralSpecies}},
                            FT, V<:AbstractVector{FT}}
    altitude_grid::AG
    energy_grid::EG
    pitch_angle_grid::PAG
    scattering::SD
    ionosphere::IO
    species::SP
    B_angle_to_zenith::FT
    s_field::V
    initialized::Bool
end

"""
    AuroraModel(altitude_lims, θ_lims, E_max, neutrals, electrons, B_angle_to_zenith=0;
                species = (N2Species(neutrals), O2Species(neutrals), OSpecies(neutrals)))

Build a lightweight `AuroraModel`. Only the grids and ionosphere are set up; the expensive
computation (scattering matrices, species densities, cross sections, cascading data) is
deferred to `initialize!(model)`, which is called automatically by `run!(sim)`.

## Inputs
- `altitude_lims`: altitude limits (km) for the bottom and top of the ionosphere
- `θ_lims`: pitch-angle beam limits (e.g. `180:-10:0`), 180° = field-aligned down
- `E_max`: upper energy-grid limit (eV)
- `neutrals`: a [`NeutralAtmosphere`](@ref) (from [`run_msis`](@ref), [`read_msis_file`](@ref)
  or [`read_ccmc_msis`](@ref)) or the path to an MSIS file generated by AURORA, from which the
  default N₂/O₂/O species are built. Must be `nothing` when `species` is given.
- `electrons`: an [`ElectronProfile`](@ref) (from [`run_iri`](@ref), [`read_iri_file`](@ref)
  or [`read_ccmc_iri`](@ref)) or the path to an IRI file generated by AURORA.
- `B_angle_to_zenith`: angle between the magnetic field and zenith (degrees, default 0)

## Keyword Arguments
- `species`: tuple (or any iterable) of [`NeutralSpecies`](@ref) instances that the model
  should simulate. When omitted, N₂, O₂ and O are built from `neutrals`. Pass a custom tuple
  (with `neutrals = nothing`) to add, remove, or replace species:
  ```julia
  atm = read_msis_file(msis_file)

  # Two species example:
  model = AuroraModel(..., nothing, ...; species = (O2Species(atm), OSpecies(atm)))

  # Four species example, with a custom 4th gas
  # Laws (density, cross sections, secondary law, phase) must be @law-wrapped, a functor, or
  # a named function to ensure reproducibility when saved to physics_state.jld2:
  custom_sp = NeutralSpecies(:MyGas, @law(z -> 1e18 .* exp.(-z ./ 30e3));
                             elastic_cross_section = AURORA.e_N2elastic,
                             channels = [CollisionChannel("exc", AURORA.e_N2a3sup, 6.17, 0),
                                         CollisionChannel("ion", AURORA.e_N2ionx2sgp, 15.6, 1)],
                             secondary_law = @law((E_s, E_p) -> 1 / (11.4^2 + E_s^2)),
                             phase_fcn_generator = phase_fcn_N2)
  model = AuroraModel(..., nothing, ...; species = (N2Species(atm), O2Species(atm),
                                                     OSpecies(atm),   custom_sp))

  # A species' channel table can be edited before run!/initialize!
  push!(model.species[:N2].channels, CollisionChannel("mystate", my_sigma, 9.0, 0))
  run!(sim)
  ```

## Returns
An uninitialized `AuroraModel`. Call `initialize!(model)` or `run!(sim)` to complete setup.
"""
function AuroraModel(altitude_lims, θ_lims, E_max, neutrals, electrons, B_angle_to_zenith=0;
                     species = nothing)
    if species === nothing && neutrals === nothing
        throw(ArgumentError("AuroraModel needs either a neutral atmosphere (`neutrals`) " *
                             "or an explicit `species` tuple"))
    elseif species !== nothing && neutrals !== nothing
        throw(ArgumentError("`neutrals` is not used when `species` is given; pass " *
                             "`neutrals = nothing` (the species already carry their own " *
                             "density sources)"))
    end
    if species === nothing
        neutrals = to_neutral_source(neutrals)
        species  = (N2Species(neutrals), O2Species(neutrals), OSpecies(neutrals))
    end
    altitude_grid    = AltitudeGrid(altitude_lims[1], altitude_lims[2])
    energy_grid      = EnergyGrid(E_max)
    pitch_angle_grid = PitchAngleGrid(θ_lims)
    ionosphere       = Ionosphere(electrons, altitude_grid.h)
    species_tuple    = Tuple(species)
    scattering       = ScatteringData()
    s_field          = altitude_grid.h ./ cosd(B_angle_to_zenith)

    FT = promote_type(eltype(s_field), typeof(B_angle_to_zenith))

    return AuroraModel{typeof(altitude_grid), typeof(energy_grid), typeof(pitch_angle_grid),
                       typeof(scattering), typeof(ionosphere), typeof(species_tuple),
                       FT, typeof(s_field)}(
        altitude_grid, energy_grid, pitch_angle_grid,
        scattering, ionosphere, species_tuple,
        FT(B_angle_to_zenith), s_field, false
    )
end

# Reassigning a grid, species, or the B-field geometry invalidates every derived quantity
# (scattering, densities, cross sections, cascading, and any simulation workspace built from
# this model). We intercept those assignments to mark the model uninitialized, which lets `run!` /
# `initialize!(sim)` detect the change and rebuild automatically.
function Base.setproperty!(model::AuroraModel, name::Symbol, value)
    ty = fieldtype(typeof(model), name)
    setfield!(model, name, value isa ty ? value : convert(ty, value))
    if name in (:altitude_grid, :energy_grid, :pitch_angle_grid, :species, :B_angle_to_zenith)
        setfield!(model, :initialized, false)
    end
    return value
end

"""
    initialize!(model::AuroraModel; verbose=true, policy=CachePolicy())

Perform all heavy setup for `model`:
1. Compute `s_field` and `ionosphere` from the current altitude grid.
2. Compute (or load from cache) the scattering matrices.
3. For each species: sample the density profile, derive the cross-section, excitation-level
   and cascading data from the species' collision channels, build phase functions, and
   load/compute cascading transfer matrices.

Called internally by `initialize!(sim)` and/or `run!(sim)`.
"""
function initialize!(model::AuroraModel;
                     verbose::Bool = true,
                     policy::CachePolicy = CachePolicy())
    model.s_field    = model.altitude_grid.h ./ cosd(model.B_angle_to_zenith)
    model.ionosphere = Ionosphere(model.ionosphere.electron_source, model.altitude_grid.h)
    model.scattering = ScatteringData(model.pitch_angle_grid; verbose, policy)

    h  = model.altitude_grid.h
    eg = model.energy_grid
    θ  = model.scattering.θ_scatter

    for sp in model.species
        sp.density = collect(Float64, sp.density_source(h))
        rebuild_collision_data!(sp, eg.E_centers)
        check_cross_sections_zero_below_energy_loss(sp, eg)
        sp.phase_fcn = sp.phase_fcn_generator(θ, eg.E_centers)
    end
    # Check before the cascading matrices: they are expensive, and would be cached for a
    # grid that is then refused.
    check_bins_narrower_than_ionization_threshold(eg, model.species)
    check_threshold_bin_products_below_floor(eg, model.species)
    for sp in model.species
        load_or_compute_cascading!(sp.cascading_data, eg; verbose, policy)
        check_ionizing_rows_have_events(sp, eg)
    end
    model.initialized = true
    return nothing
end

"""
    check_bins_narrower_than_ionization_threshold(energy_grid, species)

Throw an `ArgumentError` if any energy bin is wider than the smallest ionization
threshold of any species.

The ionization bookkeeping is split between two code paths that are only consistent as
long as every ionizing collision moves the primary electron out of its energy bin:
`update_B!` retains the in-bin fraction `max(0, 1 - E_loss/ΔE)` of the scattered flux
(zero whenever `ΔE < E_loss`), while the cascading matrices used in
`compute_ionization_spectra!` redistribute one full primary (and its secondaries) to
strictly lower bins. If a bin is wider than an ionization threshold, both paths are
active at once for that channel and each ionizing collision produces up to ~2 primary
electrons (and over-counted secondaries), breaking particle and energy conservation.

The default grid from `make_energy_grid` saturates at ΔE ≈ 11.65 eV, below the default
ionization thresholds of N2, O2 and O, so this only triggers for custom coarse grids or
custom species with low ionization thresholds.
"""
function check_bins_narrower_than_ionization_threshold(energy_grid, species)
    i_widest = argmax(energy_grid.ΔE)
    ΔE_max = energy_grid.ΔE[i_widest]
    offenders = String[]
    for sp in species
        E_levels = sp.excitation_levels
        ionizing = axes(E_levels, 1)[2:end]
        thresholds = [E_levels[i, 1] for i in ionizing if E_levels[i, 2] > 0]
        isempty(thresholds) && continue
        threshold_min = minimum(thresholds)
        if ΔE_max > threshold_min
            push!(offenders, "$(sp.name) ($(round(threshold_min; digits = 2)) eV)")
        end
    end
    if !isempty(offenders)
        throw(ArgumentError(
            "The widest energy bin (bin $(i_widest), ΔE = $(round(ΔE_max; digits = 2)) eV) " *
            "is wider than the lowest ionization threshold of " * join(offenders, ", ") *
            ". Ionizing collisions in bins wider than the threshold over-count primary " *
            "and secondary electrons. Use an energy grid whose bins all stay narrower " *
            "than every ionization threshold."
        ))
    end
    return nothing
end

"""
    check_cross_sections_zero_below_energy_loss(sp, energy_grid)

Throw an `ArgumentError` if any cross section of `sp` is non-zero at a bin center below
that channel's energy loss. A collision cannot happen below its energy loss, so such bins
would remove electrons that are never placed elsewhere on the grid. The built-in
cross-section library satisfies this.
"""
# Row `i_level` of a species' cross-section matrix, for messages.
channel_label(sp, i_level) =
    i_level == 1 ? "elastic cross section" : "channel $(sp.channels[i_level - 1].name)"

function check_cross_sections_zero_below_energy_loss(sp, energy_grid)
    E_centers = energy_grid.E_centers
    for i_level in axes(sp.excitation_levels, 1)
        E_loss = sp.excitation_levels[i_level, 1]
        below = findall(i -> E_centers[i] < E_loss && sp.cross_sections[i_level, i] > 0,
                        eachindex(E_centers))
        if !isempty(below)
            throw(ArgumentError(
                "$(sp.name) $(channel_label(sp, i_level)) has a non-zero cross section below its " *
                "energy loss of $(E_loss) eV, at bin centers " *
                "$(round.(E_centers[below]; digits = 3)) eV. A cross section must be zero " *
                "at every bin center below the channel's energy loss, where the collision " *
                "cannot happen; correct the cross-section table or the energy loss."
            ))
        end
    end
    return nothing
end

"""
    check_threshold_bin_products_below_floor(energy_grid, species)

Throw an `ArgumentError` if, for any ionizing channel, the energy bin holding the threshold
reaches higher above it than the lowest grid edge.

The cascading matrices have rows only for the bins entirely above a threshold, while
`update_A!` still removes the ionizing electrons from the bin holding it. This check
guarantees that the ionization products of that bin would all fall below the lowest grid
edge anyway, so leaving them off the grid is correct.
"""
function check_threshold_bin_products_below_floor(energy_grid, species)
    E_edges = energy_grid.E_edges
    offenders = String[]
    for sp in species
        E_levels = sp.excitation_levels
        for i in axes(E_levels, 1)[2:end]
            E_levels[i, 2] > 0 || continue
            I = E_levels[i, 1]
            ib = searchsortedfirst(E_edges, I) - 1
            (ib < 1 || ib > energy_grid.n) && continue
            gap = E_edges[ib + 1] - I
            if !(gap < E_edges[1])
                push!(offenders, "$(sp.name) channel at $(I) eV (bin $(ib) reaches \
                                  $(round(gap; digits = 2)) eV above it)")
            end
        end
    end
    if !isempty(offenders)
        throw(ArgumentError(
            "The energy bin holding an ionization threshold has no cascading row, so its " *
            "ionization products are not placed on the grid. This is only harmless when " *
            "they would all fall below the lowest grid edge " *
            "($(round(E_edges[1]; digits = 2)) eV), which fails for " *
            join(offenders, ", ") * ". Use an energy grid whose bin holding each " *
            "threshold reaches less than the lowest edge above it."
        ))
    end
    return nothing
end

"""
    check_ionizing_rows_have_events(sp, energy_grid)

Throw an `ArgumentError` if a row with ionizing cross section has no cascading events.
"""
function check_ionizing_rows_have_events(sp, energy_grid)
    E_levels = sp.excitation_levels
    for i_level in axes(E_levels, 1)[2:end]
        E_levels[i_level, 2] > 0 || continue
        E_loss = E_levels[i_level, 1]
        for iE in 1:energy_grid.n
            energy_grid.E_edges[iE] >= E_loss || continue
            σ = sp.cross_sections[i_level, iE]
            σ > 0 || continue
            if !(event_count(sp.cascading_data, iE, E_loss) > 0)
                throw(ArgumentError(
                    "cascading matrices for $(sp.name) hold no ionization events in energy \
                     bin $(iE) for the channel at $(E_loss) eV, but its cross section there \
                     is $(σ) m²"))
            end
        end
    end
    return nothing
end


function Base.show(io::IO, model::AuroraModel)
    print(io, "AuroraModel($(model.altitude_grid), $(model.energy_grid), $(model.pitch_angle_grid))")
end

function Base.show(io::IO, ::MIME"text/plain", model::AuroraModel)
    println(io, "AuroraModel", model.initialized ? "" : " (not initialized)", ":")
    println(io, "├── ", model.altitude_grid)
    println(io, "├── ", model.energy_grid)
    println(io, "├── ", model.pitch_angle_grid)
    println(io, "├── ", model.initialized ? model.scattering : "ScatteringData: (not initialized)")
    println(io, "├── ", model.ionosphere)
    println(io, "├── Species: ", join((String(sp.name) for sp in model.species), ", "))
    print(io, "└── B angle to zenith: $(model.B_angle_to_zenith)°")
end
